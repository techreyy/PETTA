export type PageContentSlug = keyof typeof PAGE_CONTENT_DEFAULTS;
export type PageContent<S extends PageContentSlug> = (typeof PAGE_CONTENT_DEFAULTS)[S];

export function resolvePageContent<S extends PageContentSlug>(slug: S, value?: unknown): PageContent<S> {
  const source = value && typeof value === 'object' ? value as Record<string, unknown> : {};
  return Object.fromEntries(Object.entries(PAGE_CONTENT_DEFAULTS[slug]).map(([key, fallback]) => {
    const text = source[key];
    return [key, typeof text === 'string' && text.trim() ? text : fallback];
  })) as PageContent<S>;
}

// Only substitute known values; the result is rendered as escaped React text, never HTML.
export function fillCopyTemplate(text: string, values: Record<string, string>): string[] {
  // Preserve the original text-node boundaries around profile values (including font shaping).
  return text.split(/(\{\w+\})/g).filter(Boolean).map(part => {
    const key = /^\{(\w+)\}$/.exec(part)?.[1];
    return key ? values[key] ?? part : part;
  });
}
